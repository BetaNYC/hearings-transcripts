"""The What's changed page (whats-changed.html) and WHATS-CHANGED.md. Standard library only,
no network.

The standard is betanyc-ai-workspace platform/system/whats-changed-standard.md. The list on the
page is generated by scripts/whats_changed.py, a copy of the workspace's canonical file (never
edit it here). These tests run what CI would run, check the page structure the standard asks
for (section 6), and check that every page's footer links to the page.

Run from the repository root:  python3 -m unittest discover -s scripts -v
"""

from __future__ import annotations

import re
import subprocess
import sys
import unittest
from html.parser import HTMLParser
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import feedback as fb  # noqa: E402

REPO = Path(__file__).resolve().parent.parent
PAGE = REPO / fb.WHATS_CHANGED_PAGE
SCRIPT = REPO / "scripts" / "whats_changed.py"
RENDER = [sys.executable, str(SCRIPT), "render", "WHATS-CHANGED.md", "--format", "fragment",
          "--into", "whats-changed.html", "--repo-url", "https://github.com/BetaNYC/hearings-transcripts"]


def run(args: list[str]) -> subprocess.CompletedProcess:
    return subprocess.run(args, cwd=REPO, capture_output=True, text=True, timeout=60, check=False)


def published_pages() -> list[Path]:
    """Every HTML page on the site: the two at the root and everything under hearings/."""
    return [REPO / "index.html", PAGE, *sorted((REPO / "hearings").rglob("*.html"))]


def footer(page: Path) -> str:
    text = page.read_text(encoding="utf-8")
    return text[text.index("<footer>"):text.index("</footer>")]


class Tags(HTMLParser):
    def __init__(self) -> None:
        super().__init__()
        self.tags: list[tuple[str, dict]] = []
        self.text: dict[str, str] = {}
        self._open: list[str] = []

    def handle_starttag(self, tag, attrs):
        self.tags.append((tag, dict(attrs)))
        if tag in ("h1", "legend"):
            self._open.append(tag)

    def handle_endtag(self, tag):
        if self._open and self._open[-1] == tag:
            self._open.pop()

    def handle_data(self, data):
        for tag in self._open:
            self.text[tag] = self.text.get(tag, "") + data

    def find(self, tag: str, **attrs) -> list[dict]:
        return [a for t, a in self.tags if t == tag and all(a.get(k) == v for k, v in attrs.items())]


class WhatsChanged(unittest.TestCase):
    def test_file_passes_the_check(self):
        r = run([sys.executable, str(SCRIPT), "check", "WHATS-CHANGED.md"])
        self.assertEqual(r.returncode, 0, r.stdout + r.stderr)

    def test_page_matches_the_file(self):
        r = run([*RENDER, "--check"])
        self.assertEqual(r.returncode, 0, "rebuild: python3 " + " ".join(RENDER[1:]) + "\n" + r.stdout + r.stderr)

    def test_every_page_links_to_it_in_the_footer(self):
        pages = published_pages()
        self.assertGreater(len(pages), 30)
        for page in pages:
            hrefs = [h for h in re.findall(r'href="([^"]+)"', footer(page))
                     if h.endswith(fb.WHATS_CHANGED_PAGE) and "://" not in h]
            self.assertEqual(len(hrefs), 1, page.relative_to(REPO).as_posix())
            self.assertEqual((page.parent / hrefs[0]).resolve(), PAGE.resolve(), page.relative_to(REPO).as_posix())

    def test_its_own_footer_has_the_report_a_mistake_link(self):
        self.assertIn(fb.feedback_html(fb.WHATS_CHANGED_PAGE, None), footer(PAGE))

    def test_page_structure(self):
        p = Tags()
        p.feed(PAGE.read_text(encoding="utf-8"))
        self.assertEqual(len(p.find("h1")), 1)
        self.assertEqual(p.text["h1"].strip(), "What's changed")
        for tag in ("header", "nav", "main", "footer"):
            self.assertTrue(p.find(tag), f"no <{tag}>")
        self.assertTrue(p.find("a", href="#main"), "no skip link")
        self.assertTrue(p.find("main", id="main"))
        articles = p.find("article")
        self.assertEqual(len(articles), 10)
        self.assertTrue(all("aria-labelledby" in a for a in articles))
        self.assertEqual(len([a for a in p.find("time") if "datetime" in a]), 10)
        # The filter is hidden until its script runs, so with JavaScript off every entry shows.
        self.assertEqual(len(p.find("fieldset")), 1)
        wrappers = p.find("div", **{"class": "wc-filters"})
        self.assertEqual(len(wrappers), 1)
        self.assertIn("hidden", wrappers[0])
        self.assertEqual(p.text["legend"].strip(), "Show changes to")
        self.assertEqual(len(p.find("input", type="checkbox")), 4)
        self.assertTrue(any(a.get("role") == "status" and a.get("aria-live") == "polite" for _, a in p.tags))


if __name__ == "__main__":
    unittest.main()
